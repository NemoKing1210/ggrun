/**
 * `seed/iee/core.ggpack` is the source of the system pack (spec §10.2). Pure
 * tests and tools that run without a database read it as a TypeScript
 * fixture, `lib/engine/iee/core-docs/core.generated.ts`, which this renders
 * and `pnpm iee:core` writes. A test fails when the two drift apart.
 */
import { stableJson, revisionIdFor, type GgpackManifest } from "./ggpack";

export const CORE_PACK_FILE = "seed/iee/core.ggpack";
export const CORE_FIXTURE_FILE = "lib/engine/iee/core-docs/core.generated.ts";

function indent(json: string, by: string): string {
  return json
    .trimEnd()
    .split("\n")
    .map((line, i) => (i === 0 ? line : by + line))
    .join("\n");
}

/** The fixture's source text: items first, then effects, each by slug; latest revisions only. */
export function renderCoreFixture(manifest: GgpackManifest): string {
  const ordered = [
    ...manifest.entries.filter((e) => e.kind === "item"),
    ...manifest.entries.filter((e) => e.kind === "effect"),
  ];
  const out: string[] = [];
  out.push(`// GENERATED by \`pnpm iee:core\` from ${CORE_PACK_FILE}. Do not edit by hand:`);
  out.push("// change the pack (the constructor on a development install, then export it");
  out.push("// back into the file) and run `pnpm iee:core` again.");
  out.push("");
  out.push('import type { EntryDoc } from "../dsl/doc";');
  out.push("");
  out.push(`export const CORE_PACK_ID = ${JSON.stringify(manifest.pack.id)};`);
  out.push("");
  out.push("export const CORE_ENTRY_IDS = {");
  for (const e of ordered) out.push(`  ${e.slug}: ${JSON.stringify(e.id)},`);
  out.push("} as const;");
  out.push("");
  out.push("/** The latest revision of each entry, with the id every installation derives for it. */");
  out.push("export const CORE_REVISIONS: Readonly<");
  out.push("  Record<keyof typeof CORE_ENTRY_IDS, { revisionId: string; number: number; contentHash: string }>");
  out.push("> = {");
  for (const e of ordered) {
    const latest = e.revisions.at(-1)!;
    out.push(`  ${e.slug}: {`);
    out.push(`    revisionId: ${JSON.stringify(revisionIdFor(e.id, latest.contentHash))},`);
    out.push(`    number: ${latest.number},`);
    out.push(`    contentHash: ${JSON.stringify(latest.contentHash)},`);
    out.push("  },");
  }
  out.push("};");
  out.push("");
  out.push("export const CORE_DOCUMENTS: Readonly<Record<keyof typeof CORE_ENTRY_IDS, EntryDoc>> = {");
  for (const e of ordered) out.push(`  ${e.slug}: ${indent(stableJson(e.revisions.at(-1)!.doc), "  ")},`);
  out.push("};");
  out.push("");
  return out.join("\n");
}
